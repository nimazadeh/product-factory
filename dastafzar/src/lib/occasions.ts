// Iran occasions engine — two layers, because Iran's calendar has two kinds:
//  1) Solar-fixed: national/cultural days pinned to a Jalali month/day.
//  2) Lunar (Hijri): religious days pinned to a Hijri month/day — they move
//     ~11 days every Jalali year, so they are COMPUTED per displayed year by
//     scanning its days through Intl's Islamic calendar (verified against the
//     official 1405 calendar: Ashura 1448 = 4 Tir 1405 ✓; a ±1 day variance
//     vs. the official sighting-based calendar is possible for some months).
// Sources: official Iranian calendar listings for 1405 (bahesab.ir, IMNA).

