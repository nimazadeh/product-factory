const islamicFmt = new Intl.DateTimeFormat("en-u-ca-islamic", { day: "numeric", month: "numeric" });

/** All occasions of one Jalali year as a map keyed by `${jm}-${jd}`.
    Lunar days are found by scanning the year's Gregorian days. */
export function occasionsForYear(jy: number, monthLengthFn: (y: number, m: number) => number, toGregorianFn: (j: { jy: number; jm: number; jd: number }) => { gy: number; gm: number; gd: number }): Map<string, OccasionItem[]> {
  const map = new Map<string, OccasionItem[]>();
  const add = (jm: number, jd: number, item: OccasionItem) => {
    const k = `${jm}-${jd}`;
    const arr = map.get(k) ?? [];
    if (!arr.some((x) => x.title === item.title)) arr.push(item);
    map.set(k, arr);
  };
  for (const [k, items] of Object.entries(SOLAR_OCCASIONS)) {
    const [jm, jd] = k.split("-").map(Number);
    items.forEach((it) => add(jm, jd, it));
  }
  for (let jm = 1; jm <= 12; jm++) {
    const len = monthLengthFn(jy, jm);
    for (let jd = 1; jd <= len; jd++) {
      const g = toGregorianFn({ jy, jm, jd });
      const parts = islamicFmt.formatToParts(new Date(g.gy, g.gm - 1, g.gd));
      const hm = Number(parts.find((x) => x.type === "month")?.value);
      const hd = Number(parts.find((x) => x.type === "day")?.value);
      for (const l of LUNAR_OCCASIONS) if (l.hm === hm && l.hd === hd) add(jm, jd, { title: l.title, holiday: l.holiday });
    }
  }
  return map;
}
